// Writes the Looks' CSS into styles.css (between the "looks:" markers) and their textures into textures/, from the
// themes lab (themes-lab.html) and Nhat's pinned variants (looks.json → pins). Run: node design/export-looks.mjs.
// Needs Google Chrome (CHROME_PATH) and cwebp (brew install webp).
//
// The lab's own code expands each pin into tokens (lookVars) and rules (lookRules). Its textures are SVGs with
// feTurbulence filters; Safari redraws an SVG background on every paint, which stutters while scrolling on an
// iPhone, so each filtered texture is drawn once here into an image file at its tile size (1 CSS px = 1 image px):
//   --paper-tex     opaque JPEG, the texture laid over that mode's paper colour (it is always the page's bottom layer)
//   leather grain   opaque JPEG over mid-grey: the Look overlays and soft-lights it, which a grey matches exactly
//   the rest        WebP with alpha (cwebp): the Look lays them over gradients, normal blending
// Filter-free SVGs stay SVG: inline when small, else a file (the Ukiyo-e seigaiha waves).
// A texture used by several Looks or both modes is one file. A rule that doesn't match never fetches its image, so a
// browser only loads the chosen Look's files, in the current mode.
// Day is the Look's base (no data-theme, or light); night is data-theme="dark", or no data-theme on a dark system.
import puppeteer from 'puppeteer-core';
import {execFileSync} from 'node:child_process';
import {mkdirSync,mkdtempSync,readFileSync,readdirSync,rmSync,unlinkSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const here=dirname(fileURLToPath(import.meta.url)),root=join(here,'..'),cssPath=join(root,'styles.css'),texDir=join(root,'textures');
const CHROME=process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const {pins}=JSON.parse(readFileSync(join(here,'looks.json'),'utf8'));
const START='/* looks: generated by design/export-looks.mjs from design/looks.json; edit the lab and rerun */',END='/* end looks */';
// --inline keeps the filtered SVGs inline instead (for comparing on a phone; ~110 KB of CSS for the three Looks)
const INLINE=process.argv.includes('--inline'),JPEG_Q=0.92,WEBP=['-q','50','-alpha_q','40','-m','6'];
try{execFileSync('cwebp',['-version']);}catch{console.error('cwebp not found: brew install webp');process.exit(1);}

const browser=await puppeteer.launch({executablePath:CHROME,headless:true});
let looks;
try{
  const page=await browser.newPage();
  await page.goto(pathToFileURL(join(here,'themes-lab.html')).href+'#api');
  await page.waitForFunction(()=>window.themeLab);
  looks=await page.evaluate(async(pins,jpegQ,inline)=>{
    const {defaults,tokens,lookVars,lookRules}=window.themeLab;
    const FIELD={'--paper-tex':'paperTex','--chrome-tex':'chromeTex','--plank-tex':'plankTex'};
    const drawn=new Map();
    // an SVG texture → { key, kind, ext, data }: drawn once at its tile size, over bg when it is opaque
    async function draw(url,bg,kind){
      const key=url+'|'+bg;if(drawn.has(key)) return drawn.get(key);
      const src=url.slice(5,-2),svg=decodeURIComponent(src.slice(src.indexOf(',')+1));
      const w=+svg.match(/width='(\d+)'/)[1],h=+svg.match(/height='(\d+)'/)[1];
      const img=new Image();img.src=src;await img.decode();
      const c=document.createElement('canvas');c.width=w;c.height=h;const x=c.getContext('2d');
      if(bg){x.fillStyle=bg;x.fillRect(0,0,w,h);}
      x.drawImage(img,0,0,w,h);
      const out={key,kind,ext:bg?'jpg':'webp',data:bg?c.toDataURL('image/jpeg',jpegQ):c.toDataURL('image/png')};
      drawn.set(key,out);return out;
    }
    const looks=[];
    for(const pin of pins){
      const dir=pin.direction,c=Object.assign(defaults(dir),pin.cfg),T=tokens(dir,c),modes={};
      for(const mode of ['day','night']){
        const t=T[mode],decls=[];
        for(const d of lookVars(dir,mode,t)){
          const i=d.indexOf(':'),k=d.slice(0,i),v=d.slice(i+1);
          if(!v.startsWith('url("data:image/svg+xml,')){decls.push([k,v]);continue;}
          const svg=decodeURIComponent(v.slice(v.indexOf(',')+1,-2));
          // a filter-free SVG stays one: inline when small, else a file (the seigaiha tiles are ~10 KB each)
          if(!svg.includes('<filter')){if(v.length<2000) decls.push([k,v]);else decls.push([k,{tex:{key:svg,kind:k.slice(2),ext:'svg',data:svg},mode}]);continue;}
          if(inline){decls.push([k,v]);continue;}
          const kind=t[FIELD[k]].desc.split(' ')[0],bg=k==='--paper-tex'?t.paper:kind==='leather'?'#808080':null;
          decls.push([k,{tex:await draw(v,bg,kind),mode}]);
        }
        modes[mode]={decls,leaf:t.leaf};
      }
      looks.push({dir,name:pin.name,modes,rules:lookRules(dir,c).trim()});
    }
    return looks;
  },pins,JPEG_Q,INLINE);
}finally{await browser.close();}

// Name each texture by its kind, plus the mode when it differs by mode, plus the Look on a clash
const uses=new Map();
for(const l of looks) for(const m of Object.values(l.modes)) for(const [,v] of m.decls) if(v.tex){
  const u=uses.get(v.tex.key)||{tex:v.tex,modes:new Set(),dirs:new Set()};u.modes.add(v.mode);u.dirs.add(l.dir);uses.set(v.tex.key,u);
}
const base=u=>u.tex.kind+(u.modes.size===1?'-'+[...u.modes][0]:'');
const names=new Map(),count={};
for(const u of uses.values()) count[base(u)]=(count[base(u)]||0)+1;
for(const [key,u] of uses) names.set(key,`${count[base(u)]>1?[...u.dirs][0]+'-':''}${base(u)}.${u.tex.ext}`);

mkdirSync(texDir,{recursive:true});
const tmp=mkdtempSync(join(tmpdir(),'looks-'));
for(const [key,u] of uses){
  const name=names.get(key),bytes=u.tex.ext==='svg'?null:Buffer.from(u.tex.data.split(',')[1],'base64');
  if(u.tex.ext==='svg') writeFileSync(join(texDir,name),u.tex.data);
  else if(u.tex.ext==='jpg') writeFileSync(join(texDir,name),bytes);
  else{const png=join(tmp,name+'.png');writeFileSync(png,bytes);execFileSync('cwebp',['-quiet',...WEBP,png,'-o',join(texDir,name)]);}
}
rmSync(tmp,{recursive:true,force:true});
const made=new Set(names.values());
for(const f of readdirSync(texDir)) if(!made.has(f)) unlinkSync(join(texDir,f));

const vars=decls=>decls.map(([k,v])=>`${k}:${v.tex?`url(textures/${names.get(v.tex.key)})`:v}`).join(';');
let css='';
for(const {dir,name,modes:{day,night},rules} of looks){
  const L=`:root[data-look="${dir}"]`,N=vars(night.decls);
  css+=`/* ${name} */\n${L}{${vars(day.decls)}}\n${L} .book{--leaf:${day.leaf}}\n`+
    `${L}[data-theme="dark"]{${N}}\n${L}[data-theme="dark"] .book{--leaf:${night.leaf}}\n`+
    `@media (prefers-color-scheme:dark){${L}:not([data-theme="light"]){${N}}${L}:not([data-theme="light"]) .book{--leaf:${night.leaf}}}\n`+
    rules+'\n';
}
const old=readFileSync(cssPath,'utf8'),a=old.indexOf(START),b=old.indexOf(END);
const block=`${START}\n${css}${END}\n`;
writeFileSync(cssPath,a<0?old.trimEnd()+'\n'+block:old.slice(0,a)+block+old.slice(b+END.length+1));
const kb=f=>readFileSync(join(texDir,f)).length/1024;
console.log(`styles.css: looks block ${(block.length/1024).toFixed(0)} KB`);
for(const f of [...made].sort()) console.log(`textures/${f}: ${kb(f).toFixed(1)} KB`);
for(const l of looks) for(const mode of ['day','night']){
  const fs=new Set(l.modes[mode].decls.filter(([,v])=>v.tex).map(([,v])=>names.get(v.tex.key)));
  console.log(`${l.dir} ${mode}: ${[...fs].reduce((s,f)=>s+kb(f),0).toFixed(0)} KB (${[...fs].join(', ')})`);
}
