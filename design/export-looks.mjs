// Writes the Looks' CSS into styles.css (between the "looks:" markers) from the themes lab (themes-lab.html) and
// Nhat's pinned variants (looks.json → pins). Run: node design/export-looks.mjs. Needs Google Chrome (CHROME_PATH).
//
// The lab's own code expands each pin into tokens (lookVars) and rules (lookRules). Its textures are SVGs with
// feTurbulence filters; Safari re-rasterises an SVG background on every paint, which would stutter while
// scrolling on an iPhone, so each filtered texture is drawn once here into a PNG data URI. Filter-free SVGs (the
// Ukiyo-e waves) stay as SVG.
// Day is the Look's base (no data-theme, or light); night is data-theme="dark", or no data-theme on a dark system.
// WIP: as written the block is ~2 MB (10 distinct textures, 20–160 KB each as WebP 0.7 data URIs, repeated per mode
// and per night selector; PNG made it ~6 MB), far too big for styles.css. Not run into styles.css yet.
import puppeteer from 'puppeteer-core';
import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const here=dirname(fileURLToPath(import.meta.url)),cssPath=join(here,'..','styles.css');
const CHROME=process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const {pins}=JSON.parse(readFileSync(join(here,'looks.json'),'utf8'));
const START='/* looks: generated by design/export-looks.mjs from design/looks.json; edit the lab and rerun */',END='/* end looks */';

const browser=await puppeteer.launch({executablePath:CHROME,headless:true});
let css;
try{
  const page=await browser.newPage();
  await page.goto(pathToFileURL(join(here,'themes-lab.html')).href+'#api');
  await page.waitForFunction(()=>window.themeLab);
  css=await page.evaluate(async pins=>{
    const {defaults,tokens,lookVars,lookRules}=window.themeLab;
    const png=new Map();
    // url("data:image/svg+xml,…") with a <filter> → a bitmap data URI, drawn once at the tile's size
    async function raster(url){
      if(png.has(url)) return png.get(url);
      const src=url.slice(5,-2),svg=decodeURIComponent(src.slice(src.indexOf(',')+1));
      const w=+svg.match(/width='(\d+)'/)[1],h=+svg.match(/height='(\d+)'/)[1];
      const img=new Image();img.src=src;await img.decode();
      const c=document.createElement('canvas');c.width=w;c.height=h;c.getContext('2d').drawImage(img,0,0,w,h);
      const out=`url(${c.toDataURL('image/webp',0.7)})`;png.set(url,out);return out;
    }
    async function bake(decls){
      const out=[];
      for(const d of decls){
        const i=d.indexOf(':'),k=d.slice(0,i);let v=d.slice(i+1);
        if(v.startsWith('url("data:image/svg+xml,')&&decodeURIComponent(v).includes('<filter')) v=await raster(v);
        out.push(`${k}:${v}`);
      }
      return out.join(';');
    }
    let s='';
    for(const pin of pins){
      const dir=pin.direction,c=Object.assign(defaults(dir),pin.cfg),T=tokens(dir,c),L=`:root[data-look="${dir}"]`;
      const day=await bake(lookVars(dir,'day',T.day)),night=await bake(lookVars(dir,'night',T.night));
      s+=`/* ${pin.name} */\n${L}{${day}}\n${L} .book{--leaf:${T.day.leaf}}\n`+
        `${L}[data-theme="dark"]{${night}}\n${L}[data-theme="dark"] .book{--leaf:${T.night.leaf}}\n`+
        `@media (prefers-color-scheme:dark){${L}:not([data-theme="light"]){${night}}${L}:not([data-theme="light"]) .book{--leaf:${T.night.leaf}}}\n`+
        lookRules(dir,c).trim()+'\n';
    }
    return s;
  },pins);
}finally{await browser.close();}

const old=readFileSync(cssPath,'utf8'),a=old.indexOf(START),b=old.indexOf(END);
const block=`${START}\n${css}${END}\n`;
writeFileSync(cssPath,a<0?old.trimEnd()+'\n'+block:old.slice(0,a)+block+old.slice(b+END.length+1));
console.log(`styles.css: looks block ${(block.length/1024).toFixed(0)} KB`);
